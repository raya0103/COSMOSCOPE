# Quick lookup indexes
TARGETS_BY_ID: Dict[str, Dict[str, Any]] = {t["id"]: t for t in EXTENDED_ASTRONOMICAL_CATALOG}
CHALLENGE_TARGETS: List[Dict[str, Any]] = [t for t in EXTENDED_ASTRONOMICAL_CATALOG if t["is_challenge_target"]]

def get_targets(
    category: Optional[str] = None,
    challenge_only: bool = False,
    status: Optional[str] = None
) -> List[Dict[str, Any]]:
    """Returns filtered catalog targets."""
    res = EXTENDED_ASTRONOMICAL_CATALOG
    if challenge_only:
        res = [t for t in res if t["is_challenge_target"]]
    if category and category.lower() != "all":
        res = [t for t in res if t["category"].lower() == category.lower()]
    if status:
        res = [t for t in res if t["status"].lower() == status.lower()]
    return res

def get_target_by_id(target_id: str) -> Optional[Dict[str, Any]]:
    return TARGETS_BY_ID.get(target_id)
